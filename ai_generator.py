def generate_post_drafts(source_articles: list[dict], count: int = 3) -> list[dict]:
    articles_text = "\n\n".join(
        f"[{i+1}] 主題：{a['title']}\n角度：{a.get('summary','')}"
        for i, a in enumerate(source_articles[:5])
    )

    system = f"""{ACCOUNT_PERSONA}

你的任務是根據提供的主題，生成 Threads 發文草稿。

規則：
- 每篇草稿不超過 450 字（含標點）
- 絕對不加任何 hashtag 或 # 字號
- 開頭要有反差感或吸睛的第一句話
- 不直接推銷保險商品
- 結尾用問句引發互動
- 輸出嚴格為 JSON array，不加任何說明文字，不加 markdown 符號
- JSON 格式：[{{"draft":"內文","angle":"切入角度","source_title":"主題標題"}}]

【絕對禁止——違反請重寫】
- 禁止說「保險歸保險、投資歸投資」——這句話否定投資型保單的存在價值
- 禁止將投資型保單定性為「有錢人才能碰」「保障缺口填滿才能考慮」「費用高所以不划算」
- 投資型保單正確立場：壽險成本極低（自然費率）是最大優勢，保障彈性高，是很好用的工具
- 禁止對任何險種給出優先順序、先後次序、或暗示某險種「比較不重要」
- 禁止說「意外險保費低最後補」「意外險相對不重要」等降級意外險的說法
"""

    user = f"""請根據以下主題，生成 {count} 篇風格各異的 Threads 發文草稿：

{articles_text}

輸出 JSON array，{count} 個物件。"""

    raw = _call_claude(system, user, max_tokens=2000)
    clean = raw.replace("```json", "").replace("```", "").strip()
    drafts = json.loads(clean)[:count]

    # 合規審查並修正每篇草稿
    for d in drafts:
        d["draft"] = _apply_compliance(d["draft"])

    return drafts


def generate_reply(
    post_text: str,
    comment_text: str,
    commenter_username: str,
    conversation_history: Optional[list[dict]] = None,
) -> str:
    history_text = ""
    if conversation_history:
        history_text = "\n".join(
            f"@{m['username']}: {m['text']}"
            for m in conversation_history[-4:]
        )

    system = f"""{ACCOUNT_PERSONA}

你正在回覆 Threads 上的留言。

規則：
- 不超過 150 字，直接輸出回覆文字，不加說明或引號，不加 hashtag
- 適當換行，每個觀點各自一行
- 說話像個有經驗的朋友說真話，有立場，不說模糊答案
- 可用「不是…而是…」句式或生活類比說清楚觀念
- 不用「首先」「其次」「確實」「這個問題很好」等 AI 慣用詞
- 若是問題，給出有立場的實質回答；若是閒聊，輕鬆有個性地回應
- 若有購買意向或想深入了解，自然引導對方私訊
"""

    context = f"""我的貼文內容：
{post_text}

{"對話記錄：" + history_text if history_text else ""}

@{commenter_username} 留言說：
{comment_text}

請回覆這則留言："""

    reply = _call_claude(system, context, max_tokens=300)
    return _apply_compliance(reply)


