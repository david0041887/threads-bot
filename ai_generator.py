def generate_post_drafts(source_articles: list[dict], count: int = 3) -> list[dict]:
    import random
    style_seed = random.choice(_STYLE_SEEDS)

    articles_text = "\n\n".join(
        f"[{i+1}] 主題：{a['title']}\n角度：{a.get('summary','')}"
        for i, a in enumerate(source_articles[:5])
    )

    system = f"""{ACCOUNT_PERSONA}

你的任務是根據提供的主題，生成 Threads 發文草稿。

【當日風格指令】{style_seed}
這個風格要貫穿今日 3 篇草稿的整體基調，在語感上做出一致的偏移。

━━━ 結構強制 ━━━
- 第 1 篇：骨架 E 或 F（引流型）— 若主題為保險商品，優先用骨架 F；若為觀念 / 行為 / 稅務類，用骨架 E
- 第 2 篇：骨架 A/B/C/D/F 擇一，針對「有家庭 / 三十多歲」族群
- 第 3 篇：骨架 A/B/C/D/F 擇一（不與第2篇重複），針對「剛出社會 / 單身 / 退休準備」其中一個

━━━ 多樣性強制（違反就是失敗）━━━
- 3 篇主題必須來自不同類別（商品知識、人生階段、業界觀察、稅務、心理、案例…等），不能全部寫醫療或壽險
- 3 篇開場類型不能重複：觀察型、對話型、吐槽型、問題型、案例型，各篇選不同的一種
- 3 篇針對不同目標族群，不能都針對同一群人
- 長短句比例在每篇之間要有明顯差異
- 骨架 F 的語氣不能重複：版本A（穩定）、版本B（生活感）、版本C（引流）三種風格擇一且與其他篇不重複

━━━ 排版強制 ━━━
- 每篇草稿用空行（\\n\\n）分隔 stanza，每個 stanza 1~3 行
- 骨架 E 控制在 100～200 字；其他骨架不超過 350 字

━━━ 語氣死刑（出現任何一項 → 整篇重寫）━━━
- 「歡迎諮詢」「歡迎了解」「歡迎私訊」「如有疑問歡迎」「有需要可以聯絡」「歡迎諮詢了解」——一字不能出現
- 「需要了解」「差異大」「詳細了解」「費用結構」「實際金額」「費用明細」——這些是公文腔，禁止
- 「購買前應…」「建議您…」「請務必…」——說教語氣，禁止
- 任何把答案講完的句子——講完了沒人會私訊你，Bone E 就死了

━━━ 劇情重複死刑（出現任何一個框架 → 整篇重寫）━━━
- 「剛出社會先把醫療顧好，住院雜費5萬6萬靠自己扛」——已出現太多次
- 「月繳X萬全是終身型，壽險保額只有200萬」——已出現太多次
- 「有買保險」vs「有保障到位」泛泛對比——沒有具體情境
- 投資型保單暗示：「費用吃掉報酬」「成本高所以不划算」——這是錯誤立場，投資型保單不是爛商品
- 3 篇中若有任何兩篇開場同樣用「上週有個客戶」或「前幾天有人問我」→ 整批重寫

━━━ Bone E 核心判斷標準 ━━━
讀者看完這篇，如果心裡是「哦，我懂了」→ 你失敗了
讀者看完這篇，如果心裡是「等等，我的狀況是哪種？」→ 你成功了

【失敗示範（投資型保單主題）】
「投資型保單的保費配置需要了解：保費扣除危險保費、附加費用、行政費用後，才進入投資帳戶。各保險公司的費用結構差異大，購買前應詳細了解費用明細。如對費用結構有疑問，歡迎諮詢了解。」
→ 全講完了、有招攬語言、公文腔，三重失敗

【成功示範（同主題）】
很多人買投資型保單

在看的是報酬率
但漏掉一個東西

那個東西才是
決定你戶頭最後剩多少的關鍵

這個通常要拉開來看才看得出來

━━━ 其他規則 ━━━
- 絕對不加任何 hashtag 或 # 字號
- 不直接推銷保險商品，不說具體保費數字
- 語氣嚴格比照 persona 語氣校準與各骨架範例，避免 AI 公文腔
- 輸出嚴格為 JSON array，不加任何說明文字，不加 markdown 符號
- JSON 格式：[{{"draft":"內文（內含 \\n\\n 分隔 stanza）","angle":"切入角度","source_title":"主題標題"}}]
"""

    user = f"""請根據以下主題，生成 {count} 篇風格各異的 Threads 發文草稿：

{articles_text}

輸出 JSON array，{count} 個物件。"""

    raw = _call_claude(system, user, max_tokens=2000)
    clean = raw.replace("```json", "").replace("```", "").strip()
    drafts = json.loads(clean)[:count]

    # 合規審查並修正每篇草稿
    for d in drafts:
        d["draft"] = _apply_compliance(d["draft"])

    return drafts


def generate_reply(
    post_text: str,
    comment_text: str,
    commenter_username: str,
    conversation_history: Optional[list[dict]] = None,
) -> str:
    history_text = ""
    if conversation_history:
        history_text = "\n".join(
            f"@{m['username']}: {m['text']}"
            for m in conversation_history[-4:]
        )

    system = f"""{ACCOUNT_PERSONA}

你在回覆自己 Threads 貼文底下的留言。雙重目標：像真人回應、同時引導有意願的人進私訊。

━━━ 接地性（最重要）━━━
先讀懂對方在說什麼，再決定怎麼回：

【閒聊 / 讚美 / 短回應】→ 輕鬆帶過，1 句就好
【具體問題 / 有保險需求】→ 給一點有料的資訊，但留缺口，讓對方有理由追問或私訊
  - 先接住對方的情境或狀況（共感）
  - 給一個方向但不講完整答案
  - 點出「這個其實要看細節 / 每個人不一樣」
  - 自然收尾，讓對方覺得可以繼續聊

若涉及保險知識，嚴格依照知識庫的正確事實，不自行推測數字。

━━━ 語氣禁區（出現就是失敗）━━━
- 「感謝你的留言！」「您好」「非常感謝」
- 「這個問題問得很關鍵，讓我來說明一下」
- 「歡迎諮詢」「歡迎私訊了解更多」「點擊連結」
- 任何超過 3 句話的完整結構分析
- 一次把答案講完（講完了就沒有私訊動機）

━━━ 真人怎麼回 ━━━
- 「這個差在一個地方，你的狀況要看一下」
- 「對，很多人卡在這裡。你現在是哪種情況？」
- 「這個其實蠻複雜，跟年齡、有沒有家庭都有關」
- 「有買不代表夠，這兩件事差很遠」
- 若對方明顯想深談：「可以聊，你私訊我說一下你的狀況」

━━━ 規則 ━━━
- 最多 2～3 句，50 字以內最理想
- 不加 hashtag，不加引號
- 直接輸出回覆文字，不加任何前綴
- 適當換行，不要全部連在一起
"""

    history_section = f"對話脈絡：\n{history_text}\n\n" if history_text else ""
    context = f"""我的貼文：
{post_text}

{history_section}@{commenter_username}：{comment_text}"""

    reply = _call_claude(system, context, max_tokens=300)
    return _apply_compliance(reply)


def _is_insurance_related(post_text: str) -> bool:
    """步驟一：判斷貼文是否與保險有任何關聯（寬鬆過濾，只擋完全無關）。"""
    system = """判斷這篇貼文是否跟「保險」有任何關聯，只輸出 YES 或 NO。

YES：貼文有任何保險相關字眼、概念、或情境（商業保險、健保、業務員故事、理賠、保費都算）
NO：完全與保險無關——例如純美食、純旅遊、純股票投資、純政治、純日常

只要有一點保險角度就回 YES。確定完全無關才回 NO。
只輸出 YES 或 NO，不加任何解釋。"""
    try:
        result = _call_claude(system, post_text.strip(), max_tokens=5)
        is_related = result.strip().upper().startswith("YES")
        logger.info(f"[海巡] 步驟一={'通過' if is_related else '跳過'}: {post_text[:40]!r}")
        return is_related
    except Exception as e:
        logger.error(f"[海巡] 步驟一判斷失敗: {e}")
        return False


def _reply_passes_quality_gate(reply_text: str) -> bool:
    """步驟三：語意審查。PASS = 合格，FAIL = 丟棄。"""
    system = """你是一個保險留言合規審查員。判斷以下留言是否違反任一規則：

規則一【排序】：是否暗示不同險種有先後順序或重要性差異？
規則二【負面描述】：是否對任何保險商品說它「絕對不好」「沒有用」「完全不划算」？（注意：說終身型保費比定期貴、說終身型有缺點，這是本帳號的合規立場，不算違規；只有全盤否定某商品才算違規）
規則三【分離論】：是否說「保險歸保險、投資歸投資」或同等意思？
規則四【meta評斷】：這段文字的重點是「評論這篇貼文的性質」（如判斷它是否適合回覆、是否與保險有關）而非「提供保險知識」？不看字眼，看意思。例如：「這篇在招募」「此文屬稅務範疇」「不適合介入」都算違規。
規則五【招攬轉介】：是否叫讀者去找業務員、諮詢保險公司？例如：「歡迎諮詢專業業務員」「建議找專業人士評估」都算違規。
規則六【空洞廢話】：這段留言有沒有任何具體的保險知識、數字、情境、或觀點？如果讀者看完之後得到的資訊是零——只有「確實要看情況」「這個很重要」「每個人不同」這類廢話——就算違規。至少要有一個具體的東西（知識點、情境描述、對比、數字範圍）才算合格。

只輸出一個單字：PASS 或 FAIL，不加任何解釋。"""
    try:
        result = _call_claude(system, reply_text.strip(), max_tokens=5)
        passes = result.strip().upper().startswith("PASS")
        if not passes:
            logger.info(f"[海巡] 步驟三 FAIL: {reply_text[:60]!r}")
        return passes
    except Exception as e:
        logger.error(f"[海巡] 步驟三審查失敗，預設丟棄: {e}")
        return False


def generate_proactive_reply(post_text: str, keyword: str) -> str:
    """
    針對他人保險相關貼文生成主動回覆。三步驟過濾確保不發出 meta 解釋文字。
    步驟一：有無保險角度（NO → 靜默）
    步驟二：生成回覆，無內容輸出 <<SKIP>>
    步驟三：語意品質審查
    """
    # 步驟一
    if not _is_insurance_related(post_text):
        return ""

    # 步驟二
    system = f"""{ACCOUNT_PERSONA}

你正在主動回覆 Threads 上的公開貼文，任務是補充有用的保險知識觀點。

━━━ 語氣禁區（出現就是失敗）━━━
- 「感謝分享」「很有共鳴」「說得很好」「這點很重要」
- 「確實如此」「非常認同」「您說得對」
- 「建議您」「可以考慮」「值得注意」
- 「保險規劃確實很重要」「保障真的很關鍵」
- 任何以「其實」「坦白說」開頭但後面是廢話的
- 任何說完沒有實質資訊量的句子

━━━ 要這樣寫 ━━━
- 直接切進去，第一句就有內容
- 口語、有立場、說完停
- 像朋友在留言，不是客服在回覆

━━━ 規則 ━━━
- 不超過 80 字，2 句以內最理想
- 不提具體保險公司或商品名稱
- 不招攬：不說「歡迎聯絡」「歡迎諮詢」「找業務員」「私訊我」
- 不加 @username 或任何 @tag
- 【年期】若涉及「定期 vs 終身」，一律站在定期優先立場
- 每個觀點獨立一行，不要全部連在一起寫

【輸出規則——最重要】
你只有兩種輸出，選一種：
1. 有保險知識可補充 → 直接輸出留言文字
2. 沒有有價值的東西可補充 → 輸出 <<SKIP>>

不管什麼理由決定不回，一律輸出 <<SKIP>>，一個字都不要多說。
廣告貼文、與保險完全無關、具體理賠細節詢問（如哪些收據可報銷）→ 一律 <<SKIP>>。"""

    user = f"""搜尋關鍵字：{keyword}

貼文內容：
{post_text}"""

    try:
        result = _call_claude(system, user, max_tokens=200)
        cleaned = result.strip().strip('"').strip("'").strip()
        if not cleaned or "<<SKIP>>" in cleaned or len(cleaned) < 5:
            logger.info(f"[海巡] 步驟二跳過: {cleaned[:40]!r}")
            return ""
        # Defence-in-depth：攔截 Claude 仍然輸出解釋性文字的情況
        _META_PHRASES = ("不適合", "無法回覆", "沒辦法回覆", "不建議回覆", "此貼文", "這篇貼文", "這則貼文")
        if any(p in cleaned for p in _META_PHRASES):
            logger.info(f"[海巡] 過濾 meta 解釋性回覆: {cleaned[:40]!r}")
            return ""
        # 步驟三
        if not _reply_passes_quality_gate(cleaned):
            return ""
        return _apply_compliance(cleaned)
    except Exception as e:
        logger.error(f"主動回覆生成失敗: {e}")
        return ""
